"""Mirror lint acceptance cases in isolated repository trees."""

import contextlib
import io
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

import mirror_lint


class MirrorLintTests(unittest.TestCase):
    def scan(self, files):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name, text in files.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
            return mirror_lint.scan(root, list(map(Path, files)))

    def test_source_includes(self):
        cases = [
            ('crates/a/tests/check.rs', 'include_str!("../src/lib.rs");', True),
            ('crates/a/tests/check.rs', 'include_bytes!("../src/lib.rs");', True),
            ('crates/a/tests/check.rs', 'include_str!(r#"../src/lib.rs"#);', True),
            ('crates/a/tests/check.rs', '// include_str!("../src/lib.rs");', False),
            ('crates/a/tests/check.rs', 'include_str!("fixtures/input.rs");', False),
            ('crates/a/src/lib.rs', '#[cfg(test)] mod tests { const S: &str = include_str!("logic.rs"); }', True),
            ('crates/a/src/lib.rs', 'const S: &str = include_str!("logic.rs");', False),
            ('tests/test_a.py', 'from pathlib import Path\nx = Path("pkg/src/a.py").read_text()', True),
            ('tests/test_a.py', 'from pathlib import Path\nROOT = Path(__file__).resolve().parents[1]\nx = (ROOT / "pkg" / "src" / "a.py").read_bytes()', True),
            ('tests/test_a.py', 'x = open("pkg/src/a.py").read()', True),
            ('tests/test_a.py', 'x = open("pkg/src/tests/a.py").read()', False),
            ('tests/test_a.py', 'x = "mirror of imaginary"\n# include_str!("../src/lib.rs")', False),
        ]
        for name, source, expected in cases:
            with self.subTest(name=name, source=source):
                files = {'crates/a/src/lib.rs': '', 'crates/a/src/logic.rs': '',
                         'pkg/src/a.py': '', 'pkg/src/tests/a.py': '', name: source}
                result = self.scan(files)
                self.assertEqual((name, 'source-include') in result, expected, result)

    def test_frozen_copies(self):
        for count, expected in [(12, True), (11, False)]:
            with self.subTest(count=count):
                text = '\n'.join(f'let value_{i} = compute_value({i});' for i in range(count))
                result = self.scan({'a/src/lib.rs': text, 'a/tests/fixtures/old.rs': text})
                self.assertEqual(('a/tests/fixtures/old.rs', 'frozen-copy') in result, expected)
        text = '\n'.join(['use example::module;', '{', '}', 'import example'] * 20)
        self.assertEqual(self.scan({'a/src/lib.rs': text, 'a/tests/copy.rs': text}), set())
        imports = 'from example import (\n' + '\n'.join(
            f'    imported_symbol_{i},' for i in range(15)) + '\n)'
        self.assertEqual(self.scan({'a/src/lib.py': imports, 'tests/test_a.py': imports}), set())

    def test_declarations_only_in_comments_or_docstrings(self):
        for source, expected in [
            ('# read-only mirror', True), ('"""Mirror of foo.bar."""', True),
            ('# Mirrors foo.bar', True), ('# MIRROR: foo', True),
            ('# git mirror URL', False), ('value = "mirror of foo"', False),
            ('# git mirrors upstream repositories', False),
            ('"""Check mirrors and their exceptions."""', False),
        ]:
            with self.subTest(source=source):
                result = self.scan({'a/src/a.py': source})
                self.assertEqual(('a/src/a.py', 'self-declared') in result, expected)
        self.assertIn(('a/src/lib.rs', 'self-declared'), self.scan({
            'a/src/lib.rs': '// read-only mirror of foo\nfn main() {}',
        }))

    def test_schemas(self):
        path = 'workers/src/p/schemas/a.json'
        cases = [
            ({}, True),
            ({'crates/contracts/generated/manifest.json': json.dumps({'files': [{'path': path}]})}, False),
            ({'crates/contracts/tests/schema_drift.rs': f'const X: &str = include_str!("../../../{path}");'}, False),
        ]
        for extra, expected in cases:
            with self.subTest(extra=extra):
                result = self.scan({path: '{}', **extra})
                self.assertEqual((path, 'ungenerated-schema') in result, expected)
        self.assertEqual(self.scan({'spec.schema.json': '{"$comment": "Generated by Rust"}'}), set())
        self.assertIn(('spec.schema.json', 'ungenerated-schema'), self.scan({'spec.schema.json': '{}'}))

    def test_controller_schema_drift_registration(self):
        path = 'crates/controller/src/run_backend/schemas/run-backend.json'
        launch = 'crates/controller/src/run_backend/schemas/run-backend-launch-context.json'
        unknown = 'crates/controller/src/run_backend/schemas/unregistered.json'
        drift = 'crates/controller/tests/run_backend_cli.rs'
        includes = (
            'include_str!("../src/run_backend/schemas/run-backend.json");\n'
            'include_str!("../src/run_backend/schemas/run-backend-launch-context.json");'
        )
        for manifest in (False, True):
            with self.subTest(manifest=manifest):
                files = {path: '{}', launch: '{}', unknown: '{}', drift: includes}
                files['crates/controller/tests/unregistered_drift.rs'] = (
                    'include_str!("../src/run_backend/schemas/unregistered.json");'
                )
                if manifest:
                    files['workers/src/p/schemas/a.json'] = '{}'
                    files['crates/contracts/generated/manifest.json'] = json.dumps({
                        'files': [{'path': 'workers/src/p/schemas/a.json'}],
                    })
                result = self.scan(files)
                self.assertNotIn((path, 'ungenerated-schema'), result)
                self.assertNotIn((launch, 'ungenerated-schema'), result)
                self.assertIn((unknown, 'ungenerated-schema'), result)
                self.assertNotIn(('workers/src/p/schemas/a.json', 'ungenerated-schema'), result)

    def test_ratchet(self):
        offender = ('tests/test_a.py', 'source-include')
        entry = {'path': offender[0], 'detector': offender[1], 'owner': '#906'}
        self.assertEqual(mirror_lint.ratchet({offender}, [entry]), [])
        self.assertTrue(mirror_lint.ratchet({offender}, []))
        self.assertTrue(mirror_lint.ratchet(set(), [entry]))

    def test_mutation_helpers_are_not_source_includes(self):
        for body in [
            'source = Path("pkg/src/a.py")\ntext = source.read_text()\nsource.write_text(text.replace("old", "new"))',
            'Path("pkg/src/a.py").write_bytes(Path("pkg/src/a.py").read_bytes())',
            'text = open("pkg/src/a.py").read()\nopen("pkg/src/a.py", "w").write(text)',
        ]:
            with self.subTest(body=body):
                self.assertNotIn(('tests/test_mutant.py', 'source-include'), self.scan({
                    'pkg/src/a.py': '', 'tests/test_mutant.py': 'from pathlib import Path\n' + body,
                }))
        result = self.scan({
            'pkg/src/a.py': '', 'pkg/src/b.py': '',
            'tests/test_mutant.py': 'from pathlib import Path\nx = Path("pkg/src/a.py").read_text()\nPath("pkg/src/b.py").write_text(x)',
        })
        self.assertIn(('tests/test_mutant.py', 'source-include'), result)

    def test_rust_test_files_are_not_production(self):
        for target in ['pkg/src/tests.rs', 'pkg/src/test.rs', 'pkg/src/tests/mod.rs']:
            with self.subTest(target=target):
                result = self.scan({target: '', 'pkg/tests/check.rs': f'include_str!("../../{target}");'})
                self.assertNotIn(('pkg/tests/check.rs', 'source-include'), result)
                result = self.scan({target: 'include_str!("/unused");', 'pkg/src/lib.rs': ''})
                self.assertTrue(mirror_lint.is_test(Path(target)))
        result = self.scan({
            'pkg/src/lib.rs': '',
            'pkg/src/unit.rs': '#![cfg(test)]\nconst SOURCE: &str = include_str!("lib.rs");',
            'pkg/tests/check.rs': 'include_str!("../src/unit.rs");',
        })
        self.assertIn(('pkg/src/unit.rs', 'source-include'), result)
        self.assertNotIn(('pkg/tests/check.rs', 'source-include'), result)
        text = '\n'.join(f'let value_{i} = compute_value({i});' for i in range(12))
        result = self.scan({'pkg/src/unit.rs': '#![cfg(test)]\n' + text, 'pkg/tests/copy.rs': text})
        self.assertNotIn(('pkg/tests/copy.rs', 'frozen-copy'), result)

    def test_production_outside_src(self):
        for source in ['tools/ci/helper.py', 'crates/a/tools/helper.py', 'crates/a/build.rs']:
            with self.subTest(source=source):
                text = '\n'.join(f'value_{i} = compute_value({i})' for i in range(12))
                result = self.scan({source: text, 'tests/test_copy.py': text})
                self.assertIn(('tests/test_copy.py', 'frozen-copy'), result)
                result = self.scan({source: '', 'tests/test_read.py': f'open("{source}").read()'})
                self.assertIn(('tests/test_read.py', 'source-include'), result)

    def test_comments_and_licenses_are_not_copies(self):
        for prefix, suffix in [('# ', '.py'), ('// ', '.rs'), (' * ', '.rs')]:
            text = '\n'.join(f'{prefix}Copyright license clause number {i}' for i in range(12))
            if prefix == ' * ':
                text = '/* SPDX-License-Identifier: MIT\n' + text + '\n */'
            with self.subTest(prefix=prefix):
                result = self.scan({f'pkg/src/lib{suffix}': text, f'tests/copy{suffix}': text})
                self.assertNotIn((f'tests/copy{suffix}', 'frozen-copy'), result)

    def test_owners_require_issue_references(self):
        offender = ('tests/test_a.py', 'source-include')
        for owner in ['unassigned', 'controller-cleanup', '#not-an-issue']:
            with self.subTest(owner=owner):
                entry = {'path': offender[0], 'detector': offender[1], 'owner': owner}
                self.assertTrue(mirror_lint.ratchet({offender}, [entry]))

    def test_main_enforces_allowlist_from_repository(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            offender = root / 'tests/test_read.py'
            offender.parent.mkdir()
            offender.write_text('open("tools/helper.py").read()')
            (root / 'tools').mkdir()
            (root / 'tools/helper.py').write_text('value = 1')
            allow = root / mirror_lint.ALLOWLIST
            allow.parent.mkdir(parents=True)
            subprocess.run(['git', 'init', '-q', str(root)], check=True)
            subprocess.run(['git', '-C', str(root), 'add', '.'], check=True)
            entry = {'path': 'tests/test_read.py', 'detector': 'source-include', 'owner': '#906'}
            for entries, present, expected, message in [
                ([], True, 1, 'new offender'),
                ([entry], True, 0, '0 errors'),
                ([entry], False, 1, 'stale allowlist'),
                ([], False, 0, '0 errors'),
            ]:
                with self.subTest(entries=entries, present=present):
                    allow.write_text(json.dumps(entries))
                    offender.write_text('open("tools/helper.py").read()' if present else 'pass')
                    output = io.StringIO()
                    with contextlib.redirect_stdout(output):
                        status = mirror_lint.main(['--root', str(root)])
                    self.assertEqual(status, expected, output.getvalue())
                    self.assertIn(message, output.getvalue())


if __name__ == '__main__':
    unittest.main()
