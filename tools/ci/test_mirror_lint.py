"""Mirror lint acceptance cases in isolated repository trees."""

import json
from pathlib import Path
import tempfile
import unittest

import mirror_lint


class MirrorLintTests(unittest.TestCase):
    def scan(self, files):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name, text in files.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
            return mirror_lint.scan(root, list(map(Path, files)))

    def test_source_includes(self):
        cases = [
            ('crates/a/tests/check.rs', 'include_str!("../src/lib.rs");', True),
            ('crates/a/tests/check.rs', 'include_bytes!("../src/lib.rs");', True),
            ('crates/a/tests/check.rs', 'include_str!(r#"../src/lib.rs"#);', True),
            ('crates/a/tests/check.rs', '// include_str!("../src/lib.rs");', False),
            ('crates/a/tests/check.rs', 'include_str!("fixtures/input.rs");', False),
            ('crates/a/src/lib.rs', '#[cfg(test)] mod tests { const S: &str = include_str!("logic.rs"); }', True),
            ('crates/a/src/lib.rs', 'const S: &str = include_str!("logic.rs");', False),
            ('tests/test_a.py', 'from pathlib import Path\nx = Path("pkg/src/a.py").read_text()', True),
            ('tests/test_a.py', 'from pathlib import Path\nROOT = Path(__file__).resolve().parents[1]\nx = (ROOT / "pkg" / "src" / "a.py").read_bytes()', True),
            ('tests/test_a.py', 'x = open("pkg/src/a.py").read()', True),
            ('tests/test_a.py', 'x = open("pkg/src/tests/a.py").read()', False),
            ('tests/test_a.py', 'x = "mirror of imaginary"\n# include_str!("../src/lib.rs")', False),
        ]
        for name, source, expected in cases:
            with self.subTest(name=name, source=source):
                files = {'crates/a/src/lib.rs': '', 'crates/a/src/logic.rs': '',
                         'pkg/src/a.py': '', 'pkg/src/tests/a.py': '', name: source}
                result = self.scan(files)
                self.assertEqual((name, 'source-include') in result, expected, result)

    def test_frozen_copies(self):
        for count, expected in [(12, True), (11, False)]:
            with self.subTest(count=count):
                text = '\n'.join(f'let value_{i} = compute_value({i});' for i in range(count))
                result = self.scan({'a/src/lib.rs': text, 'a/tests/fixtures/old.rs': text})
                self.assertEqual(('a/tests/fixtures/old.rs', 'frozen-copy') in result, expected)
        text = '\n'.join(['use example::module;', '{', '}', 'import example'] * 20)
        self.assertEqual(self.scan({'a/src/lib.rs': text, 'a/tests/copy.rs': text}), set())
        imports = 'from example import (\n' + '\n'.join(
            f'    imported_symbol_{i},' for i in range(15)) + '\n)'
        self.assertEqual(self.scan({'a/src/lib.py': imports, 'tests/test_a.py': imports}), set())

    def test_declarations_only_in_comments_or_docstrings(self):
        for source, expected in [
            ('# read-only mirror', True), ('"""Mirror of foo.bar."""', True),
            ('# Mirrors foo.bar', True), ('# MIRROR: foo', True),
            ('# git mirror URL', False), ('value = "mirror of foo"', False),
            ('# git mirrors upstream repositories', False),
            ('"""Check mirrors and their exceptions."""', False),
        ]:
            with self.subTest(source=source):
                result = self.scan({'a/src/a.py': source})
                self.assertEqual(('a/src/a.py', 'self-declared') in result, expected)
        self.assertIn(('a/src/lib.rs', 'self-declared'), self.scan({
            'a/src/lib.rs': '// read-only mirror of foo\nfn main() {}',
        }))

    def test_schemas(self):
        path = 'workers/src/p/schemas/a.json'
        cases = [
            ({}, True),
            ({'crates/contracts/generated/manifest.json': json.dumps({'files': [{'path': path}]})}, False),
            ({'crates/contracts/tests/schema_drift.rs': f'const X: &str = include_str!("../../../{path}");'}, False),
        ]
        for extra, expected in cases:
            with self.subTest(extra=extra):
                result = self.scan({path: '{}', **extra})
                self.assertEqual((path, 'ungenerated-schema') in result, expected)
        self.assertEqual(self.scan({'spec.schema.json': '{"$comment": "Generated by Rust"}'}), set())
        self.assertIn(('spec.schema.json', 'ungenerated-schema'), self.scan({'spec.schema.json': '{}'}))

    def test_ratchet(self):
        offender = ('tests/test_a.py', 'source-include')
        entry = {'path': offender[0], 'detector': offender[1], 'owner': '#906'}
        self.assertEqual(mirror_lint.ratchet({offender}, [entry]), [])
        self.assertTrue(mirror_lint.ratchet({offender}, []))
        self.assertTrue(mirror_lint.ratchet(set(), [entry]))


if __name__ == '__main__':
    unittest.main()
