"""Write crates/*/BUILD.bazel from `cargo metadata`. Cargo stays the source of truth.

Each BUILD file holds only Cargo facts: local dependencies, unified features,
binaries, examples and the [[test]] entries that Cargo's auto-discovery would
not find. tools/bazel/rust.bzl turns them into targets.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[2]
HEADER = '# Generated by tools/bazel/generate.sh from `cargo metadata`. Do not edit.\n'


def cargo():
    found = shutil.which('cargo') or Path.home() / '.cargo/bin/cargo'
    return os.environ.get('CARGO', str(found))


def metadata(root=ROOT):
    output = subprocess.check_output(
        [cargo(), 'metadata', '--no-deps', '--format-version', '1', '--locked',
         '--manifest-path', str(root / 'Cargo.toml')], cwd=root)
    return json.loads(output)


def auto_discovered(name, relative):
    """Cargo finds tests/NAME.rs and tests/NAME/main.rs without a [[test]] entry."""
    return relative in (f'tests/{name}.rs', f'tests/{name}/main.rs')


def unified_features(packages):
    """Cargo unifies a workspace crate's features across its dependents."""
    names = {package['name'] for package in packages}
    features = {name: set() for name in names}
    for package in packages:
        for dependency in package['dependencies']:
            if dependency['name'] in names and dependency['kind'] in (None, 'dev'):
                features[dependency['name']].update(dependency['features'])
    return features


def label(directory, path):
    path = Path(os.path.normpath(path))
    if path.is_relative_to(directory):
        return str(path.relative_to(directory))
    relative = path.relative_to(ROOT)
    return f'//{relative.parent}:{relative.name}'


def render(package, directory, features):
    crate = package['name'].replace('-', '_')
    manifest = tomllib.loads((directory / 'Cargo.toml').read_text())
    harness = {test['name']: test.get('harness', True) for test in manifest.get('test', [])}
    local = sorted(
        f'//{Path(dependency["path"]).relative_to(ROOT)}:{dependency["name"].replace("-", "_")}'
        for dependency in package['dependencies'] if dependency.get('path'))
    bins, examples, declared = [], {}, {}
    build_script = False
    for target in package['targets']:
        kind = target['kind'][0]
        source = label(directory, target['src_path'])
        if kind == 'bin':
            if source != f'src/bin/{target["name"]}.rs':
                raise SystemExit(f'{directory}: binary {target["name"]} must live in src/bin')
            bins.append(target['name'])
        elif kind == 'example':
            examples[target['name']] = source
        elif kind == 'test':
            name = target['name']
            if not auto_discovered(name, source) or not harness.get(name, True):
                declared[name] = {'path': source, **({} if harness.get(name, True) else {'harness': False})}
        elif kind == 'custom-build':
            build_script = True
        elif kind != 'lib':
            raise SystemExit(f'{directory}: unsupported Cargo target kind {kind}')
    fields = [('package', package['name']), ('crate', crate), ('build_script', build_script),
              ('local_deps', local), ('features', sorted(features)), ('bins', sorted(bins)),
              ('examples', dict(sorted(examples.items()))),
              ('declared_tests', dict(sorted(declared.items())))]
    body = ''.join(f'    {key} = {block(value)},\n' for key, value in fields
                   if value or key in ('package', 'crate'))
    return (f'{HEADER}load("//tools/bazel:rust.bzl", "tl3_crate")\n\n'
            f'package(default_visibility = ["//visibility:public"])\n\ntl3_crate(\n{body})\n')


def starlark(value):
    if isinstance(value, bool):
        return repr(value)
    if isinstance(value, list):
        return '[' + ', '.join(map(starlark, value)) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(f'{starlark(k)}: {starlark(v)}' for k, v in value.items()) + '}'
    return json.dumps(value)


def block(value):
    """One entry per line, so concurrent [[test]] additions merge cleanly."""
    if isinstance(value, list) and len(value) > 1:
        return '[\n' + ''.join(f'        {starlark(item)},\n' for item in value) + '    ]'
    if isinstance(value, dict) and len(value) > 1:
        return '{\n' + ''.join(f'        {starlark(k)}: {starlark(v)},\n' for k, v in value.items()) + '    }'
    return starlark(value)


def expected_builds(data):
    features = unified_features(data['packages'])
    return {Path(package['manifest_path']).parent / 'BUILD.bazel':
            render(package, Path(package['manifest_path']).parent, features[package['name']])
            for package in data['packages']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for destination, expected in sorted(expected_builds(metadata()).items()):
        if args.check:
            if not destination.exists() or destination.read_text() != expected:
                stale.append(str(destination.relative_to(ROOT)))
        else:
            destination.write_text(expected)
    if stale:
        raise SystemExit('Stale Rust BUILD files: ' + ', '.join(stale)
                         + '\nRegenerate them: tools/bazel/generate.sh')


if __name__ == '__main__':
    main()
