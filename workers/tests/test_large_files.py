@pytest.mark.parametrize("header,patterns", [
    ("", ["**/BUILD.bazel"]),
    ("# Generated by tools/bazel/generate.sh. Do not edit.\n", []),
    ("// @generated\n", []),
])
def test_generated_output_fits_as_regeneration_work(tmp_path, monkeypatch, header, patterns):
    from tl3_workers.forecast import Forecaster

    (tmp_path / "tests").mkdir()
    (tmp_path / "tests/BUILD.bazel").write_text(header + 'py_test(name = "sample")\n' * 300_000)
    (tmp_path / "helper.py").write_text("def endpoint(): return '/tmp/socket'\n")
    monkeypatch.chdir(tmp_path)
    forecaster = Forecaster({"fit_tokens": 100_000, "context_tokens": 150_000,
                             "overhead_tokens": {"making": 84_000},
                             "generated_files": patterns, "generator": "tools/bazel/generate.sh"})
    forecast = forecaster.measure("Add one socket helper.", ["tests/BUILD.bazel", "helper.py"])
    assert forecast["fits"] is True, forecast
    assert forecast["file_tokens"]["tests/BUILD.bazel"] == 1024
    notes = "\n".join(forecaster.notes())
    assert "tests/BUILD.bazel" in notes and "tools/bazel/generate.sh" in notes
    assert "regenerate" in notes.lower() and "hand-edit" in notes


