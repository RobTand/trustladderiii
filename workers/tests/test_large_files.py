def test_maker_receives_generated_regeneration_guidance(maker_request, monkeypatch):  # noqa: F811
    from langchain_core.language_models.fake_chat_models import FakeMessagesListChatModel
    from langchain_core.messages import AIMessage
    from tl3_workers import runtime

    root = Path(maker_request["worktree"])
    (root / "BUILD.bazel").write_text("# Generated by build.py\n" + "target()\n" * 100_000)
    maker_request["inputs"]["plan"]["files"].append("BUILD.bazel")
    observed = []

    class RecordingModel(FakeMessagesListChatModel):
        def bind_tools(self, tools, **kwargs):
            return self

        def _generate(self, messages, **kwargs):
            observed.extend(m.content for m in messages)
            return super()._generate(messages, **kwargs)

    reply = {"kind": "needs_files", "files": [{"path": "helper.py", "why": "Needed."}]}
    model = RecordingModel(responses=[AIMessage(**turn(reply))])
    monkeypatch.setattr(runtime, "create_model", lambda request: model)
    runtime.run(maker_request, lambda event: None)
    context = "\n".join(observed)
    assert "BUILD.bazel" in context and "regenerate" in context.lower() and "hand-edit" in context
    assert "target()" not in context


