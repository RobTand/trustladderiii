#!/usr/bin/env python3
"""Copy assertion functions unchanged into the larger-world generator scope."""
from pathlib import Path
import hashlib,json,re
D=Path(__file__).resolve().parent
source=(D.parents[2]/'src/proofs.rs').read_text()
names=['check_apply','check_fail_fast_diverts','adoption_preparation','check_adoption_at_most_once','check_adoption_has_no_maker_credit','check_dependency_delivery','check_dependency_waiting','check_gate_grant','check_gate_planning','publishing_ci_transition','check_publishing_ci_tests','check_publishing_ci_earlier_step','check_gate_leaf_progress','check_pool_grant_order','check_pool_order_is_strict_priority']
functions=[];rows=[]
for name in names:
 text=re.search(r'^fn '+name+r'\([^\n]*(?:\n(?!}).*)*?\n}',source,re.M)[0]
 functions.append(text)
 rows.append(dict(function=name,source_sha256=hashlib.sha256(text.encode()).hexdigest(),copy_sha256=hashlib.sha256(text.encode()).hexdigest()))
(D/'b_beyond_checks.rs').write_text('// Generated by sync_beyond.py. Assertion functions are verbatim.\n'+'\n\n'.join(functions)+'\n')
(D/'b_beyond_hashes.json').write_text(json.dumps(rows,indent=2)+'\n')
