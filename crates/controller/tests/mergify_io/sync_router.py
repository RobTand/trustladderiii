"""Copy the real executor boundary for #830's recorded router differential.

No forwarded method is replaced by a shared behavioral shim. Both execute and
reconcile retain their complete production bodies. The production router is
compiled directly with include!; only its leaf I/O types are recorded.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = Path(__file__).resolve().parent


def block(text, marker):
    start = text.index(marker)
    brace = text.index('{', start)
    depth = 1
    cursor = brace + 1
    while depth:
        if text[cursor] == '{':
            depth += 1
        elif text[cursor] == '}':
            depth -= 1
        cursor += 1
    return text[start:cursor]


def generated():
    executor = (ROOT / 'src/executor.rs').read_text()
    adapter = (ROOT / 'src/adapters/mergify.rs').read_text()
    implementation = block(adapter, 'impl Executor for Adapter {')
    trait = '\n\n'.join(block(executor, marker) for marker in
                        ['pub enum Look {', 'pub enum WaitRecord {', 'pub trait Executor {'])
    methods = '\n\n'.join(block(implementation, marker) for marker in
                          ['    fn execute(', '    fn reconcile('])
    return {
        'router_executor.rs': '// Generated by sync_router.py from the real executor trait.\n' + trait + '\n',
        'router_current_executor.rs': '// Generated by sync_router.py. Complete real production method bodies.\n'
                                      + 'impl executor::Executor for Adapter {\n' + methods + '\n}\n',
    }


if __name__ == '__main__':
    for name, source in generated().items():
        (DEST / name).write_text(source)
