"""Regenerate CC-P's source-identity-checked replay bodies, without executing Rust."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
SOURCE = 'crates/controller/src/adapters/prismabuild.rs'
BASE = 'cdacce8f99c28ca8dba8f5f76831b77b4dfcd836'
METHODS = ('job', 'retire_node', 'fence', 'plan_failure', 'submit', 'remove_input',
           'targets', 'check_result', 'watch_wait', 'retire', 'execute', 'reconcile')
FREE = ('encoded', 'write', 'read_job', 'node_root', 'record_path',
        'node_job_paths', 'retire_superseded')
# Match Rust strings/comments before braces, including raw strings in submit's env.
TOKENS = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|r(#+)"[\s\S]*?"\1|"(?:\\.|[^"\\])*"|[{}]')


def extract(source, name, method):
    pattern = rf'^{"    " if method else ""}(?:pub )?fn {name}\('
    matches = list(re.finditer(pattern, source, re.M))
    # Fake::execute/reconcile are not the real adapter.
    match = matches[-1]
    opened = False
    depth = 0
    for token in TOKENS.finditer(source, match.start()):
        if token.group() == '{':
            depth += 1
            opened = True
        elif token.group() == '}':
            depth -= 1
            if opened and depth == 0:
                return source[match.start():token.end()]
    raise RuntimeError(f'unclosed Rust function {name}')


def replay(source):
    methods = '\n\n'.join('// BEGIN BODY\n' + extract(source, name, True) + '\n// END BODY' for name in METHODS)
    free = '\n\n'.join('#[rustfmt::skip]\n// BEGIN BODY\n' + extract(source, name, False) + '\n// END BODY' for name in FREE)
    return ('// Generated by replay.py. Method bodies are byte-for-byte source copies.\n'
            'use super::io::*;\n' + WRAPPER + '\n#[rustfmt::skip]\nimpl Adapter {\n' + methods + '\n}\n\n' + free + '\n' + RUN)


WRAPPER = """
struct Adapter(super::io::Adapter);
impl std::ops::Deref for Adapter {
    type Target = super::io::Adapter;
    fn deref(&self) -> &Self::Target { &self.0 }
}
impl std::ops::DerefMut for Adapter {
    fn deref_mut(&mut self) -> &mut Self::Target { &mut self.0 }
}
"""
RUN = """
pub fn run(op: u8, delivery: &Delivery, wait: Option<&tl3_store::ExternalWait>) -> String {
    let mut adapter = Adapter(super::io::Adapter::fixture());
    match op % 8 {
        0 => format!("{:?}", adapter.execute(delivery)),
        1 => format!("{:?}", adapter.reconcile(delivery)),
        2 => match adapter.job(delivery) {
            Ok(Some(job)) => format!("{:?}",adapter.check_result(&job)),
            value => format!("job:{}", value.is_ok()),
        },
        3 => format!("{:?}",adapter.plan_failure(delivery)),
        4 => format!("{:?}",adapter.watch_wait(delivery,wait)),
        5 => format!("{:?}",adapter.retire(&mut tl3_store::Store)),
        6 => format!("{:?}",adapter.retire_node(delivery.node())),
        _ => format!("{:?}",retire_superseded(&adapter.settings.records, delivery)),
    }
}
"""

def format_file(path):
    subprocess.run(['/home/rob/.cargo/bin/rustup', 'run', '1.99.1', 'rustfmt',
                    '--edition', '2024', str(path)], check=True)


def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', action='store_true')
    args = parser.parse_args()
    if args.reference:
        original = subprocess.check_output(['git', 'show', f'{BASE}:{SOURCE}'], cwd=ROOT).decode()
        (HERE / 'reference.rs').write_text(replay(original))
        format_file(HERE / 'reference.rs')
    (HERE / 'extracted.rs').write_text(replay((ROOT / SOURCE).read_text()))
    format_file(HERE / 'extracted.rs')


if __name__ == '__main__':
    main()
