"""Pin CPython 3.14 semantics for the Rust planner port. Run on BuildBuddy.

Python remains the migration oracle. This is not a wire schema generator.
"""
import argparse
import ast
import hashlib
import gzip
import json
from pathlib import Path, PurePosixPath
import random
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
CRATE = Path(__file__).resolve().parents[1]


def oracle():
    path = ROOT / 'workers/src/tl3_workers/roles/planner.py'
    tree = ast.parse(path.read_text())
    names = {'EDIT_VERBS', 'ADD_VERBS', 'HOLDS', 'CLAUSES', 'WORD'}
    tree.body = [node for node in tree.body if
                 isinstance(node, ast.FunctionDef) and node.name in {'mentions', 'asks_to_edit'} or
                 isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in names for t in node.targets)]
    namespace = {'re': re}
    exec(compile(tree, str(path), 'exec'), namespace)
    return namespace


def ranges(predicate):
    result = []
    for point in range(sys.maxunicode + 1):
        if 0xD800 <= point <= 0xDFFF or not predicate(chr(point)):
            continue
        if result and result[-1][1] + 1 == point:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def unicode_source():
    tables = {
        'WORD': lambda c: bool(re.fullmatch(r'\w', c)),
        'SPACE': str.isspace,
        'DECIMAL': str.isdecimal,
        'CASED': lambda c: c.islower() or c.isupper() or c.istitle(),
        'IGNORABLE': lambda c: ('AΣ' + c + '.').lower()[1] == 'ς' and ('AΣ' + c + 'A').lower()[1] == 'σ',
    }
    lines = ['// Generated by tools/vectors.py with CPython 3.14. Do not edit.']
    for name, predicate in tables.items():
        lines.append(f'pub const {name}: &[(u32, u32)] = &[')
        lines.extend(f'    (0x{a:x}, 0x{b:x}),' for a, b in ranges(predicate))
        lines.append('];')
    lines.append('pub const LOWER: &[(u32, &str)] = &[')
    for point in range(sys.maxunicode + 1):
        c = chr(point)
        if c.lower() != c:
            escaped = ''.join('\\u{' + f'{ord(v):x}' + '}' for v in c.lower())
            lines.append(f'    (0x{point:x}, "{escaped}"),')
    lines.append('];')
    return '\n'.join(lines) + '\n'


def p2a():
    path = ROOT / 'workers/tests/planner-vectors.json.gz'
    data = path.read_bytes()
    corpus = json.loads(gzip.decompress(data))
    operations = {'prerequisites.check_prerequisites', 'recall.check_citations', 'evidence.subject_covers'}
    return {'source_sha256': hashlib.sha256(data).hexdigest(), 'english': corpus['english'],
            'globs': corpus['globs'], 'cases': [
                {**{key: c[key] for key in ('id', 'operation', 'args')},
                 'outcome': {key: value for key, value in c['outcome'].items() if key in {'return', 'error'}}}
                for c in corpus['cases'] if c['operation'] in operations]}


def generated():
    rng = random.Random(820)
    reference = oracle()
    paths = ['', '.', '/', '//', '///', 'a', 'a/b', '/a', '//a', 'a/./b', 'a//b', '.hidden', 'é', '\n', 'a\nb', 'a/../b']
    patterns = ['', '*', '**', '**/*', '**/a', 'a/**', '**/**/a', '?', '[!a]', '[^ab]', '[z-a]', '[!z-a]', '[a--b]', '[a-b-c]', '[[]', '[]a]', '[!]', '[', '\\*', '{a,b}', 'a/**b']
    globs = [{'path': path, 'pattern': pattern, 'verdict': PurePosixPath(path).full_match(pattern)} for path in paths for pattern in patterns]
    for _ in range(6000):
        path = ''.join(rng.choices('abc/._é中[]!^\\\n', k=rng.randrange(18)))
        pattern = ''.join(rng.choices('abc/.*?[]!^-\\é\n', k=rng.randrange(18)))
        globs.append({'path': path, 'pattern': pattern, 'verdict': PurePosixPath(path).full_match(pattern)})
    for _ in range(3000):
        atom = ''.join(rng.choices('abc!^-[]\\&|~é', k=rng.randrange(12)))
        pattern = '[' + atom + ']'
        path = rng.choice('abc!^-[]\\&|~é/')
        globs.append({'path': path, 'pattern': pattern, 'verdict': PurePosixPath(path).full_match(pattern)})
    english = []
    words = ['edit', 'update', 'add', 'to', 'into', 'never', 'don’t', 'unchanged', 'if', 'and', 'Fix', 'α', 'é', 'a\u0301', 'a\u200c', 'AΣ', 'AΣ\u0345', 'İ', 'a²', 'a\u2167', 'keep', 'test_api', 'tests/test_api.py', 'test_api.py', 'test_apiX', 'test_api-test_api', '', '\n', '. ', ';\u001c', '!? ', 'one', 'two', 'three']
    for _ in range(4000):
        description = ' '.join(rng.choices(words, k=rng.randrange(24)))
        test = rng.choice(['test_api', 'é', '', 'test_api-test_api', 'a', 'a²', '.'])
        found = list(reference['mentions'](description, test))
        english.append({'description': description, 'test': test, 'mentions': found,
                        'verdict': any(reference['asks_to_edit'](*item) for item in found)})
    subjects = []
    for _ in range(2000):
        chosen = rng.choice(['', 'a.py', 'a.py::C', 'a.py::C::f', 'a.py:', 'é.py::Δ'])
        subject = chosen + rng.choice(['', '::f', ':f', 'Other', '::C::f'])
        subjects.append({'chosen': chosen, 'subject': subject, 'covers': subject == chosen or subject.startswith(chosen + '::'),
                         'overlaps': subject == chosen or subject.startswith(chosen + '::') or chosen.startswith(subject + '::')})
    return {'globs': globs, 'english': english, 'subjects': subjects}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 14):
        raise SystemExit('CPython 3.14 is required')
    outputs = {CRATE / 'src/python_unicode.rs': unicode_source()}
    for name, value in [('p2a', p2a()), ('generated', generated())]:
        outputs[CRATE / f'tests/fixtures/{name}.json'] = json.dumps(value, ensure_ascii=False, indent=2) + '\n' if name == 'p2a' else ('{\n' + ',\n'.join(json.dumps(key) + ': [\n' + ',\n'.join(json.dumps(row, ensure_ascii=False, separators=(',', ':')) for row in rows) + '\n]' for key, rows in value.items()) + '\n}\n')
    for path, content in outputs.items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'stale generated file: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
        print(f'{path.relative_to(ROOT)}: {len(content.encode())} bytes', flush=True)


if __name__ == '__main__':
    main()
